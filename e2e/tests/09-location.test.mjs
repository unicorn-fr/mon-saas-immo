test('intervention : artisan ajouté au carnet, dépense créée quand elle est terminée', async () => {
  const { token } = await newAccount()
  const { propertyId } = await completeLease(token)
  const i = await api(`/properties/${propertyId}/interventions`, { method: 'POST', token, body: { title: 'Fuite sous l’évier', status: 'PLANNED', date: new Date(Date.now() + 3 * 86_400_000).toISOString().slice(0, 10), newContact: { name: 'Plomberie Martin', trade: 'plombier', phone: '06 12 34 56 78' } } })
  const contacts = (await api('/contacts', { token })).filter((c) => c.kind === 'ARTISAN')
  assert.equal(contacts.length, 1)
  // Le syndic de la fiche du logement est aussi dans le carnet.
  assert.ok((await api('/contacts', { token })).some((c) => c.kind === 'SYNDIC'))
  assert.equal(contacts[0].name, 'Plomberie Martin')
  const today = await api('/today', { token })
  assert.ok(today.upcoming.some((u) => /Fuite sous l’évier avec Plomberie Martin/.test(u.label)))
  const done = await api(`/interventions/${i.id}`, { method: 'PUT', token, body: { title: i.title, status: 'DONE', date: new Date().toISOString().slice(0, 10), contactId: contacts[0].id, costCents: 18000, expenseCategory: 'REPAIR' } })
  assert.ok(done.expenseId)
  const money = await api(`/money?year=${new Date().getFullYear()}`, { token })
  assert.ok(money.expenses.some((e) => e.amountCents === 18000 && /Plomberie Martin/.test(e.vendor)))
  const ctx = await signedInContext(browser, token)
  const page = await ctx.newPage()
  const errors = []
  watch(page, errors)
  await page.goto(`${BASE}/espace/logements/${propertyId}`)
  await page.getByText('Fuite sous l’évier').first().waitFor()
  await page.goto(`${BASE}/espace/carnet`)
  await page.getByText('Plomberie Martin').first().waitFor()
  await shot(page, 'carnet')
  await ctx.close()
  assert.deepEqual(errors, [])
})

test('corbeille : une dépense supprimée se restaure à l’identique', async () => {
  const { token } = await newAccount()
  const { propertyId } = await completeLease(token)
  const date = new Date().toISOString().slice(0, 10)
  const e = await api('/expenses', { method: 'POST', token, body: { propertyId, vendor: 'Serrurerie Dupont', category: 'REPAIR', amountCents: 9500, date } })
  await api(`/expenses/${e.id}`, { method: 'DELETE', token })
  let money = await api(`/money?year=${new Date().getFullYear()}`, { token })
  assert.ok(!money.expenses.some((x) => x.vendor === 'Serrurerie Dupont'))
  const ctx = await signedInContext(browser, token)
  const page = await ctx.newPage()
  const errors = []
  watch(page, errors)
  await page.goto(`${BASE}/espace/corbeille`)
  await page.getByText(/Serrurerie Dupont/).first().waitFor()
  await shot(page, 'corbeille')
  await page.getByRole('button', { name: 'Restaurer' }).click()
  await page.getByText('La corbeille est vide.').waitFor()
  money = await api(`/money?year=${new Date().getFullYear()}`, { token })
  assert.ok(money.expenses.some((x) => x.vendor === 'Serrurerie Dupont' && x.amountCents === 9500))
  await ctx.close()
  assert.deepEqual(errors, [])
})

